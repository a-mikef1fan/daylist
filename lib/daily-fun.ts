const MS_PER_DAY = 86_400_000

export type DayParts = { year: number; month: number; day: number }

/** Parse 'YYYY-MM-DD'. Returns null when the string is not a real calendar date. */
export function parseDateKey(value: string): DayParts | null {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value)
  if (!match) return null
  const year = Number(match[1])
  const month = Number(match[2])
  const day = Number(match[3])
  const probe = new Date(Date.UTC(year, month - 1, day))
  if (probe.getUTCFullYear() !== year || probe.getUTCMonth() !== month - 1 || probe.getUTCDate() !== day) return null
  return { year, month, day }
}

/** Format a Date using its local calendar fields, so the day matches what the viewer sees. */
export function toDateKey(date: Date): string {
  const year = String(date.getFullYear()).padStart(4, '0')
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  return `${year}-${month}-${day}`
}

/** 1-based day of the year, computed in UTC so time zones and DST cannot shift it. */
function dayOfYear({ year, month, day }: DayParts): number {
  return Math.round((Date.UTC(year, month - 1, day) - Date.UTC(year, 0, 1)) / MS_PER_DAY) + 1
}

/** Pick the fun fact for a day: a curated "on this day" entry, or a general fact as the fallback. */
export function getFunFact(parts: DayParts): DailyFact {
  const key = `${String(parts.month).padStart(2, '0')}-${String(parts.day).padStart(2, '0')}`
  const dated = ON_THIS_DAY[key]
  if (dated) return { kind: 'on-this-day', year: dated[0], text: dated[1] }
  return { kind: 'general', year: null, text: GENERAL_FACTS[dayOfYear(parts) % GENERAL_FACTS.length] }
}

/** Pick the joke for a day. The same day always gives the same joke. */
export function getJoke(parts: DayParts): string {
  return JOKES[(dayOfYear(parts) + parts.year) % JOKES.length]
}

/** Both pieces of daily content for a 'YYYY-MM-DD' key, or null when the key is invalid. */
export function getDailyFun(dateKey: string): { fact: DailyFact; joke: string } | null {
  const parts = parseDateKey(dateKey)
  if (!parts) return null
  return { fact: getFunFact(parts), joke: getJoke(parts) }
}
